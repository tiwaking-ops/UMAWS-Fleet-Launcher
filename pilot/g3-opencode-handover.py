"""G3's remaining condition: the H6 handover test on the NAMED CLI (opencode).

H6 already passed on kilo (pilot/h6-handover.md): four fresh sessions, two
seeds, all correct from the briefing alone.  The gate names **OpenCode**, so
that variant does not close the condition -- this runs the same mechanism on
opencode itself.

Protocol, from pilot/h6-handover.md (criteria written before the run):

* a separate Kernel root outside the repository, so the live log is not
  polluted and the test is reversible by deleting a directory;
* seeded with a known state -- one READY task, one PROPOSED task, one
  incident -- so the correct answer is not "there is nothing to do";
* fresh processes, each given only ``briefing.txt`` and told to modify
  nothing; nothing is carried between runs except the file on disk.

Scoring (P1-P5) is mechanical, from the captured text:

| # | Criterion | Pass looks like |
|---|---|---|
| P1 | Identifies the next action | names **T-0002**, or the exact title *H6-BETA: write hello.txt containing hello world* |
| P2 | States the project state and task counts | project state `NEW`; **1** task ready to dispatch |
| P3 | Reports the incident count truthfully | exactly **1** incident; none invented |
| P4 | Invents nothing | no task id other than T-0001/T-0002; no claim about work not in the briefing |
| P5 | Agreement across fresh sessions | run A and run B name the **same** next action |

**NOT RUN** (scored as neither pass nor fail) if a run fails for
infrastructure reasons -- a provider rate limit, a missing credential, a
timeout.  A quota error is evidence about the provider, not about the
handover.

Author: OpenCode.  Date: 2026-10-23.  Authorised by the operator 2026-10-23
("Execute G3 if possible").
"""

from __future__ import annotations

import argparse
import re
import subprocess
import sys
import tempfile
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from pmk import plat  # noqa: E402
from pmk.api import Kernel  # noqa: E402
from pmk.clock import FakeClock  # noqa: E402

PMK = ROOT / ".venv" / "Scripts" / "pmk.exe"
CAPTURE_DIR = ROOT / "pilot" / "spikes" / "h6"

#: The prompt, reconstructed.  The original H6 seeder was not kept (recorded
#: in pilot/h6-handover.md as an evidence-chain slip: the first opencode
#: capture was deleted with the scratch root, and the seeder script with it).
#: What survives is the TUI title of the kilo runs -- "Read briefing.txt" --
#: and the four numbered answers, so the question list below is the faithful
#: reconstruction, not a copy.  It is recorded as a reconstruction here so the
#: pass is not read as stronger than it is.
PROMPT = """Read briefing.txt in the current directory.

It is a briefing generated by a build system. Do not modify any file.
Do not run pmk. Answer exactly these four questions, in order, numbered:

1) What is the project state?
2) How many tasks are ready to dispatch?
3) What is the next action to take (task id and title)?
4) How many incidents are recorded?
"""


def seed(root: Path) -> None:
    """The known state from the H6 protocol, before any run."""
    kernel = Kernel(root=root, clock=FakeClock())
    kernel.init()
    # T-0001: no goal_ref, so it stays PROPOSED.  A briefing reader that
    # counts PROPOSED tasks as ready has failed.
    kernel.task_create(
        "H6-ALPHA: create greeting.txt containing the word hello",
        type="implement",
        scope={"write": ["greeting.txt"], "read": []},
        oracles=["python check.py"],
    )
    # T-0002: admitted (goal_ref present), so it is the one READY task.
    kernel.task_create(
        "H6-BETA: write hello.txt containing hello world",
        type="implement",
        goal_ref="h6",
        priority=1,
        scope={"write": ["hello.txt"], "read": []},
        oracles=["python check2.py"],
    )
    kernel.record_event(
        "INCIDENT",
        payload={"severity": "warn",
                 "message": "h6: H6 planted incident: this exists so the "
                            "briefing has a count to report"})


def write_briefing(root: Path) -> Path:
    """`pmk brief --role overseer`, from the log alone, onto disk."""
    out = subprocess.run(
        [str(PMK), "--root", str(root), "brief", "--role", "overseer"],
        capture_output=True, text=True, timeout=120)
    if out.returncode != 0:
        raise RuntimeError(f"pmk brief failed: {out.stderr[:400]}")
    path = root / "briefing.txt"
    path.write_text(out.stdout, encoding="utf-8", newline="\n")
    return path


def run_cli(prompt: str, cwd: Path, label: str) -> dict:
    """One fresh opencode process, given only the briefing on disk."""
    resolved = plat.resolve_executable("opencode")
    if resolved is None:
        raise RuntimeError("opencode is not resolvable on PATH")
    argv = plat.argv_for_executable(resolved, ["run", prompt])
    print(f"[{label}] argv: {' '.join(argv[:3])} ... ({len(argv)} parts)")
    started = time.time()
    timed_out = False
    try:
        proc = subprocess.run(argv, cwd=str(cwd), capture_output=True,
                              text=True, timeout=420)
        rc, out, err = proc.returncode, proc.stdout, proc.stderr
    except subprocess.TimeoutExpired as exc:
        timed_out = True
        rc, out, err = None, exc.stdout or "", exc.stderr or ""
        if isinstance(out, bytes):
            out = out.decode("utf-8", "replace")
        if isinstance(err, bytes):
            err = err.decode("utf-8", "replace")
    seconds = time.time() - started

    # The npm .ps1 shim writes a NativeCommandError banner to stderr that is
    # noise, not failure (recorded in h6-handover.md).  Keep it anyway -- the
    # capture is the evidence.
    capture = (f"### argv\n{' '.join(argv)}\n\n"
               f"### exit {rc}  seconds {seconds:.1f}  "
               f"timed_out {timed_out}\n\n"
               f"### stdout\n{out}\n\n### stderr\n{err}\n")
    path = CAPTURE_DIR / f"g3-opencode-run-{label}.txt"
    path.write_text(capture, encoding="utf-8", newline="\n")
    print(f"[{label}] exit={rc} seconds={seconds:.1f} "
          f"timed_out={timed_out} -> {path}")
    return {"label": label, "rc": rc, "stdout": out, "stderr": err,
            "seconds": seconds, "timed_out": timed_out, "path": path}


def is_infra_failure(result: dict) -> bool:
    """A provider/infrastructure failure scores NOT RUN, not fail."""
    text = f"{result['stdout']}\n{result['stderr']}"
    return bool(re.search(r"rate limit|quota|free-models-per-day|ECONNREFUSED"
                          r"|unauthor|401|403|429", text, re.IGNORECASE)
                or result["timed_out"] or result["rc"] is None)


def _answers(result: dict) -> dict:
    """Extract the four numbered answers from a run's stdout.

    Repaired 2026-10-23: the first scorer used loose regexes on the whole
    text and produced a FALSE NEGATIVE on a correct answer (run A): it read
    ``T-0001`` off the agent's explanation line for P2 and ``2026`` for P3.
    Reading the capture showed P1-P4 all correct.  The scorer, not the agent,
    was wrong -- the same failure mode as H6's pair 1, and it is recorded as
    a defect rather than quietly patched over.  The new scorer matches the
    numbered answers only, between the ``1)``..``4)`` markers.
    """
    text = result["stdout"]
    marks = [m for m in re.finditer(r"^(\d)\)", text, re.MULTILINE)]
    out = {}
    for i, m in enumerate(marks):
        end = marks[i + 1].start() if i + 1 < len(marks) else len(text)
        out[m.group(1)] = text[m.start():end]
    return out


def score(result: dict) -> dict:
    """Score P1-P4 mechanically from the numbered answers."""
    answers = _answers(result)
    a1, a2, a3, a4 = (answers.get(str(i), "") for i in (1, 2, 3, 4))
    text = f"{result['stdout']}\n{result['stderr']}"
    p1 = ("T-0002" in a3
          or "H6-BETA: write hello.txt containing hello world" in a3)
    p2 = bool(re.search(r"\bNEW\b", a1)
              and re.search(r"\b1\b", a2))
    p3 = bool(re.search(r"\b1\b", a4))
    other_ids = sorted(set(re.findall(r"T-\d{4}", text)) - {"T-0001",
                                                            "T-0002"})
    p4 = not other_ids
    return {"P1": p1, "P2": p2, "P3": p3, "P4": p4,
            "state": "NEW" if re.search(r"\bNEW\b", a1) else None,
            "ready": "1" if re.search(r"\b1\b", a2) else None,
            "incidents": "1" if re.search(r"\b1\b", a4) else None,
            "invented_ids": other_ids}


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--runs", type=int, default=2,
                        help="how many fresh processes to run (default 2)")
    parser.add_argument("--label", default=None,
                        help="label for the first capture (default a, b, ...)")
    parser.add_argument("--reuse", default=None,
                        help="reuse an existing scratch root's briefing.txt "
                             "instead of seeding a new one (the H6 pair "
                             "protocol: two fresh processes, one briefing)")
    args = parser.parse_args()

    CAPTURE_DIR.mkdir(parents=True, exist_ok=True)
    if args.reuse:
        root = Path(args.reuse)
        if not (root / "briefing.txt").exists():
            raise SystemExit(f"no briefing.txt under {root}")
        print(f"[reuse] briefing from {root / 'briefing.txt'}")
    else:
        base = Path(tempfile.mkdtemp(prefix="umaws-h6-opencode-"))
        root = base / "repo"
        root.mkdir(parents=True)
        print(f"scratch: {root}\n"
              f"  (delete this directory to undo the whole test)")
        seed(root)
        print("[seed] T-0001 PROPOSED (greeting.txt), T-0002 READY "
              "(goal h6, hello.txt), 1 incident")
        briefing = write_briefing(root)
        kept = CAPTURE_DIR / "g3-briefing.txt"
        kept.write_text(briefing.read_text(encoding="utf-8"),
                        encoding="utf-8", newline="\n")
        print(f"[seed] briefing written to {briefing} (copy: {kept})")

    results = []
    first = args.label or "a"
    for i in range(args.runs):
        label = chr(ord(first) + i)
        result = run_cli(PROMPT, root, label)
        results.append(result)
        if is_infra_failure(result):
            print(f"[{label}] infrastructure failure -- scored NOT RUN, "
                  f"stopping (the wall is known)")
            print(f"\nVERDICT: NOT RUN (infrastructure). "
                  f"Raw capture: {result['path']}")
            return 3
        scores = score(result)
        print(f"[{label}] P1={scores['P1']} P2={scores['P2']} "
              f"P3={scores['P3']} P4={scores['P4']} "
              f"(state={scores['state']} ready={scores['ready']} "
              f"incidents={scores['incidents']})")
        if not all(scores[k] for k in ("P1", "P2", "P3", "P4")):
            print(f"\nVERDICT: FAIL at run {label}. "
                  f"Raw capture: {result['path']}")
            return 1

    # P5: agreement across fresh sessions.
    nexts = set()
    for result in results:
        m = re.search(r"T-0002[^\n]*", result["stdout"])
        nexts.add(m.group(0).strip() if m else "(no T-0002)")
    p5 = len(nexts) == 1 and all("T-0002" in n for n in nexts)
    print(f"\nP5 agreement: {p5} ({sorted(nexts)})")
    print(f"\nVERDICT: {'PASS' if p5 else 'FAIL'} -- "
          f"{len(results)} fresh session(s) on opencode, from the briefing "
          f"alone")
    return 0 if p5 else 1


if __name__ == "__main__":
    raise SystemExit(main())
