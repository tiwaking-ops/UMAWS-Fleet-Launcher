"""Generated views (pilot v1 section 9.1).

The views are **generated, not edited**.  ``ledger.md``, ``status.md`` and
``queue.md`` are projections of the event log; invariant I13 says the views
must equal the projection.

Nothing in this module decides anything.  It reads a :class:`pmk.state.State`
and writes Markdown.
"""

from __future__ import annotations

from pathlib import Path

from .models import ACTIVE_STATES, DONE, READY, VOID
from .state import State

STATE_ORDER = ("PROPOSED", "READY", "LEASED", "SUBMITTED", "VERIFYING",
               "INTEGRATING", "REWORK", "BLOCKED", "DONE", "VOID")

STATE_MARK = {
    "PROPOSED": "·", "READY": ">", "LEASED": "*", "SUBMITTED": "+",
    "VERIFYING": "v", "INTEGRATING": "i", "REWORK": "r", "BLOCKED": "!",
    "DONE": "x", "VOID": "-",
}


def _table(headers: list[str], rows: list[list[str]]) -> list[str]:
    if not rows:
        return ["_none_", ""]
    out = ["| " + " | ".join(headers) + " |",
           "|" + "|".join("---" for _ in headers) + "|"]
    for row in rows:
        out.append("| " + " | ".join(str(c) for c in row) + " |")
    out.append("")
    return out


def render_ledger(state: State) -> str:
    """``ledger.md`` — every task, its state, and its evidence."""
    lines = ["# Task ledger", "",
             "Generated by the Kernel from the event log. Do not edit.", ""]
    counts = state.counts()
    summary = "  ".join(f"{s}={counts.get(s, 0)}" for s in STATE_ORDER
                        if counts.get(s, 0))
    lines.append(f"**Tasks:** {len(state.tasks)}   {summary}")
    lines.append("")
    rows = []
    for task in sorted(state.tasks.values(), key=lambda t: t.id):
        mark = STATE_MARK.get(task.state, "?")
        lease = state.leases.get(task.id)
        evidence = ""
        if lease:
            evidence = f"fence {lease.fence}"
        if task.state == DONE:
            evidence = evidence or f"EB-{task.id}-{task.fence}"
        rows.append([
            f"`{task.id}`", mark, task.state, task.type,
            task.title or "", task.goal_ref or "",
            f"{task.attempt}/{task.attempts.get('max', '?')}",
            evidence,
        ])
    lines += _table(["id", "", "state", "type", "title", "goal", "attempts",
                     "evidence"], rows)
    return "\n".join(lines).rstrip() + "\n"


def render_status(state: State, policy: dict) -> str:
    """``status.md`` — the one-page operational view."""
    lines = ["# Status", "",
             "Generated by the Kernel from the event log. Do not edit.", ""]
    lines.append(f"- **Project state:** {state.project_state}")
    counts = state.counts()
    lines.append(f"- **Tasks:** {len(state.tasks)} "
                 f"({', '.join(f'{s} {counts.get(s, 0)}' for s in STATE_ORDER if counts.get(s, 0))})")
    lines.append(f"- **Active leases:** {len(state.active_leases())}")
    open_items = [q for q in state.queue if q["state"] == "open"]
    lines.append(f"- **Open queue items:** {len(open_items)}")
    lines.append(f"- **Incidents:** {len(state.incidents)}")
    lines.append(f"- **Policy version:** {policy.get('version', '?')}")
    lines.append("")

    ready = state.ready_tasks()
    lines.append("## Ready tasks")
    lines.append("")
    if ready:
        rows = [[f"`{t.id}`", t.priority, t.type, t.title,
                 t.agent_hint or "-", ", ".join(t.write_scope)]
                for t in ready]
        lines += _table(["id", "prio", "type", "title", "hint", "write scope"], rows)
    else:
        lines += ["_none_", ""]

    lines.append("## Active leases")
    lines.append("")
    leases = state.active_leases()
    if leases:
        rows = []
        for task_id, lease in sorted(leases.items()):
            task = state.tasks.get(task_id)
            rows.append([
                f"`{task_id}`", lease.holder or "-", lease.agent or "-",
                lease.fence, lease.session or "-", str(lease.pid or "-"),
                lease.last_failure_class or "-",
                (task.title if task else "") or "",
            ])
        lines += _table(["task", "profile", "agent", "fence", "session", "pid",
                         "last failure", "title"], rows)
    else:
        lines += ["_none_", ""]

    if state.incidents:
        lines.append("## Incidents")
        lines.append("")
        rows = [[i["ts"], i.get("subject") or "-", i.get("severity", ""),
                 i.get("message", "")] for i in state.incidents[-25:]]
        lines += _table(["when", "subject", "severity", "message"], rows)
    return "\n".join(lines).rstrip() + "\n"


def render_queue(state: State) -> str:
    """``queue.md`` — decisions waiting for the human."""
    lines = ["# Decision queue", "",
             "Generated by the Kernel from the event log. Do not edit.", ""]
    open_items = [q for q in state.queue if q["state"] == "open"]
    decided = [q for q in state.queue if q["state"] != "open"]
    lines.append("## Open")
    lines.append("")
    if open_items:
        rows = []
        for item in open_items:
            options = ", ".join(item.get("options") or [])
            rows.append([
                item["id"],
                "**class K**" if item.get("class_k") else "normal",
                item.get("topic", ""),
                options,
                item.get("recommended", ""),
                item.get("safe_default", ""),
            ])
        lines += _table(["id", "kind", "topic", "options", "recommended",
                         "safe default"], rows)
    else:
        lines += ["_none_", ""]

    if decided:
        lines.append("## Decided")
        lines.append("")
        rows = [[i["id"], i.get("topic", ""), i.get("choice", ""),
                 i.get("decided_at", "")] for i in decided]
        lines += _table(["id", "topic", "choice", "when"], rows)
    return "\n".join(lines).rstrip() + "\n"


def render(repo, state: State, policy: dict) -> dict:
    """Write all three views."""
    from .plat import atomic_write_text
    views_dir = Path(repo.views_dir)
    views_dir.mkdir(parents=True, exist_ok=True)
    written = []
    for name, text in (
        ("ledger.md", render_ledger(state)),
        ("status.md", render_status(state, policy)),
        ("queue.md", render_queue(state)),
    ):
        target = views_dir / name
        atomic_write_text(target, text)
        written.append(str(target))
    return {"views": written}
